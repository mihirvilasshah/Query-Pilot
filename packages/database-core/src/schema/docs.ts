import { formatDataType, objectFullName, type SchemaSnapshot, type SnapObject } from "./model";
import { buildDependencyGraph } from "./graph";

export interface DocumentationInput {
  projectName: string;
  platform: string;
  versionLabel: string;
  importedAt?: string | null;
  snapshot: SchemaSnapshot;
}

const md = (s: string | null | undefined) => (s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

function tableSection(o: SnapObject, snap: SchemaSnapshot): string {
  const out: string[] = [`### ${objectFullName(o)}`, ""];
  out.push("| # | Column | Type | Nullable | Default | Key |", "|---|--------|------|----------|---------|-----|");
  const fkCols = new Set(snap.relationships.filter((r) => r.sourceObjectId === o.id && r.kind === "declared").flatMap((r) => r.sourceColumns.map((c) => c.toLowerCase())));
  for (const c of [...o.columns].sort((a, b) => a.ordinal - b.ordinal)) {
    const key = [c.primaryKey ? "PK" : "", fkCols.has(c.name.toLowerCase()) ? "FK" : "", c.identity ? "IDENTITY" : ""].filter(Boolean).join(", ");
    out.push(`| ${c.ordinal} | ${md(c.name)} | ${md(formatDataType(c))} | ${c.nullable === null ? "?" : c.nullable ? "yes" : "no"} | ${md(c.defaultValue)} | ${key} |`);
  }
  const rels = snap.relationships.filter((r) => r.sourceObjectId === o.id);
  if (rels.length) {
    out.push("", "**Foreign keys**", "");
    for (const r of rels) out.push(`- ${r.name ?? "(unnamed)"}: (${r.sourceColumns.join(", ")}) → ${r.targetSchema ? `${r.targetSchema}.` : ""}${r.targetName ?? "?"} (${r.targetColumns.join(", ")})${r.onDelete ? ` ON DELETE ${r.onDelete}` : ""}${r.kind === "inferred" ? " _(inferred, not declared)_" : ""}`);
  }
  const idx = snap.indexes.filter((i) => i.objectId === o.id);
  if (idx.length) {
    out.push("", "**Indexes**", "");
    for (const i of idx) out.push(`- ${i.name}${i.isUnique ? " (unique)" : ""}${i.isPrimaryKey ? " (primary key)" : ""}: ${i.keyColumns.map((c) => c.name + (c.descending ? " DESC" : "")).join(", ")}${i.includedColumns.length ? ` INCLUDE ${i.includedColumns.join(", ")}` : ""}`);
  }
  const cons = snap.constraints.filter((c) => c.objectId === o.id && (c.type === "check" || c.type === "unique"));
  if (cons.length) {
    out.push("", "**Constraints**", "");
    for (const c of cons) out.push(`- ${c.type.toUpperCase()} ${c.name ?? ""} ${c.type === "check" ? c.expression ?? "" : `(${c.columns.join(", ")})`}`);
  }
  out.push("");
  return out.join("\n");
}

/** Deterministic Markdown documentation generated purely from stored metadata (no AI involved). */
export function generateDocumentation(input: DocumentationInput): string {
  const { snapshot: snap } = input;
  const byType = (t: SnapObject["type"]) => snap.objects.filter((o) => o.type === t).sort((a, b) => objectFullName(a).localeCompare(objectFullName(b)));
  const tables = byType("table");
  const views = byType("view");
  const procs = byType("procedure");
  const funcs = byType("function");
  const triggers = byType("trigger");
  const byId = new Map(snap.objects.map((o) => [o.id, o]));
  const graph = buildDependencyGraph(snap);

  const out: string[] = [
    `# ${input.projectName} - Database Documentation`,
    "",
    `- **Platform:** ${input.platform}`,
    `- **Schema version:** ${input.versionLabel}`,
    ...(input.importedAt ? [`- **Imported:** ${input.importedAt}`] : []),
    "- **Generated by:** QueryPilot (deterministic output from imported metadata; no AI-generated content)",
    "",
    "## Overview",
    "",
    "| Object type | Count |",
    "|-------------|-------|",
    `| Tables | ${tables.length} |`,
    `| Views | ${views.length} |`,
    `| Stored procedures | ${procs.length} |`,
    `| Functions | ${funcs.length} |`,
    `| Triggers | ${triggers.length} |`,
    `| Indexes | ${snap.indexes.length} |`,
    `| Declared foreign keys | ${snap.relationships.filter((r) => r.kind === "declared").length} |`,
    "",
  ];

  if (tables.length) out.push("## Tables", "", ...tables.map((t) => tableSection(t, snap)));

  const routineSection = (title: string, list: SnapObject[]) => {
    if (!list.length) return;
    out.push(`## ${title}`, "");
    for (const o of list) {
      out.push(`### ${objectFullName(o)}`, "");
      const p = o.metadata.parameters;
      if (p?.length) out.push("**Parameters:** " + p.map((x) => `\`${x.name} ${x.dataType}${x.direction !== "in" ? ` ${x.direction.toUpperCase()}` : ""}\``).join(", "), "");
      if (o.metadata.returnType) out.push(`**Returns:** \`${o.metadata.returnType}\``, "");
      if (o.metadata.triggerParent) out.push(`**On:** ${o.metadata.triggerParent.schema}.${o.metadata.triggerParent.name} (${(o.metadata.triggerEvents ?? []).join(", ")})`, "");
      const deps = (snap.dependencies ?? []).filter((d) => d.sourceObjectId === o.id);
      if (deps.length) {
        out.push("**References:**", "");
        for (const d of deps) {
          const name = d.targetObjectId ? objectFullName(byId.get(d.targetObjectId) ?? { schema: "", name: "?" }) : `${d.targetSchema ? `${d.targetSchema}.` : ""}${d.targetName ?? "(dynamic)"}`;
          out.push(`- ${name} - ${d.kind.replace("_", " ")}${d.operations.length ? ` (${d.operations.join(", ")})` : ""} - _${d.confidence.replace("_", " ")}_`);
        }
        out.push("");
      }
      if (o.metadata.hasDynamicSql) out.push("> ⚠ Contains dynamic SQL; objects referenced inside dynamic strings are not listed.", "");
    }
  };
  routineSection("Views", views);
  routineSection("Stored procedures", procs);
  routineSection("Functions", funcs);
  routineSection("Triggers", triggers);

  out.push("## Limitations", "");
  out.push("- Documentation reflects only what was present in the imported schema file.");
  out.push(graph.completenessCaveat ?? "- No dynamic SQL or unresolved references were detected, but static analysis cannot see application code.");
  return out.join("\n");
}
