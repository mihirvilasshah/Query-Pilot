import type { PrimaryKeyPayload, SchemaDiff, DiffItem } from "./diff";
import { diffSchemas } from "./diff";
import { formatDataType, quoteIdent, type SchemaSnapshot, type SnapColumn, type SnapConstraint, type SnapIndex, type SnapObject, type SnapRelationship } from "./model";

export interface MigrationOptions {
  /** "comment-out" (default) emits every data-destroying statement commented out so it must be enabled deliberately. */
  destructive?: "include" | "comment-out";
  /** Internal: prevents building a rollback of the rollback. */
  skipRollback?: boolean;
}

export interface MigrationStep {
  order: number;
  title: string;
  objects: string[];
  sql: string;
  destructive: boolean;
  notes: string[];
}

export interface MigrationPlan {
  title: string;
  purpose: string;
  objectsAffected: string[];
  expectedImpact: string[];
  risks: string[];
  prerequisites: string[];
  steps: MigrationStep[];
  validationSteps: string[];
  rollbackConsiderations: string[];
  migrationSql: string;
  rollbackSql: string;
  preValidationSql: string;
  postValidationSql: string;
  checklist: string[];
  destructiveCount: number;
  requiresHumanReview: true;
}

const BANNER = [
  "-- =====================================================================",
  "-- Generated by QueryPilot. NOT EXECUTED. REQUIRES HUMAN REVIEW.",
  "-- Review every statement, test on a non-production copy and take a",
  "-- verified backup before running anything in this script.",
  "-- =====================================================================",
].join("\n");

const tableSql = (full: string): string => full.split(".").map(quoteIdent).join(".");

function asTable(full: string, i: DiffItem): string {
  return tableSql(i.table ?? full);
}

function columnDef(c: SnapColumn, withDefault = true): string {
  if (c.computed && c.computedExpression) return `${quoteIdent(c.name)} AS ${c.computedExpression}`;
  const parts = [quoteIdent(c.name), formatDataType(c)];
  if (c.identity) parts.push("IDENTITY(1,1)");
  parts.push(c.nullable === false ? "NOT NULL" : "NULL");
  if (withDefault && c.defaultValue) parts.push(`DEFAULT ${c.defaultValue}`);
  return parts.join(" ");
}

function commentOut(sql: string, reason: string): string {
  return [`-- DESTRUCTIVE - commented out. ${reason}`, ...sql.split("\n").map((l) => `-- ${l}`)].join("\n");
}

function indexSql(i: SnapIndex, table: string): string {
  const type = (i.indexType ?? "").toUpperCase();
  const cols = i.keyColumns.map((c) => `${quoteIdent(c.name)}${c.descending ? " DESC" : ""}`).join(", ");
  const isColumnstore = type.includes("COLUMNSTORE");
  const kind = type ? `${i.isUnique && !isColumnstore ? "UNIQUE " : ""}${type} ` : i.isUnique ? "UNIQUE " : "";
  let sql = `CREATE ${kind}INDEX ${quoteIdent(i.name)} ON ${table} (${cols})`;
  if (i.includedColumns.length) sql += ` INCLUDE (${i.includedColumns.map(quoteIdent).join(", ")})`;
  if (i.filterDefinition) sql += ` WHERE ${i.filterDefinition}`;
  return sql + ";";
}

type FkPayload = SnapRelationship & { targetFull?: string };

function fkSql(f: FkPayload, table: string): string {
  const name = f.name ? `CONSTRAINT ${quoteIdent(f.name)} ` : "";
  const target = (f.targetFull ?? `${f.targetSchema ?? ""}.${f.targetName ?? ""}`).replace(/^\./, "");
  let sql = `ALTER TABLE ${table} WITH CHECK ADD ${name}FOREIGN KEY (${f.sourceColumns.map(quoteIdent).join(", ")}) REFERENCES ${tableSql(target)} (${f.targetColumns.map(quoteIdent).join(", ")})`;
  if (f.onDelete && f.onDelete.toUpperCase() !== "NO ACTION") sql += ` ON DELETE ${f.onDelete.toUpperCase()}`;
  if (f.onUpdate && f.onUpdate.toUpperCase() !== "NO ACTION") sql += ` ON UPDATE ${f.onUpdate.toUpperCase()}`;
  return sql + ";";
}

function dropConstraint(table: string, name: string | null | undefined, kind: string): string {
  return name ? `ALTER TABLE ${table} DROP CONSTRAINT ${quoteIdent(name)};` : `-- MANUAL: unnamed ${kind} on ${table} cannot be dropped by name; look it up in sys.objects first.`;
}

function toCreateOrAlter(definition: string): string {
  return definition.replace(/^(\s*(?:--[^\n]*\n|\/\*[\s\S]*?\*\/\s*)*)CREATE\s+(?!OR\s+ALTER)/i, "$1CREATE OR ALTER ");
}

function routineKeyword(type: string): string {
  return type === "procedure" ? "PROCEDURE" : type.toUpperCase();
}

export function generateMigration(
  base: SchemaSnapshot,
  target: SchemaSnapshot,
  options: MigrationOptions = {},
  precomputedDiff?: SchemaDiff,
): MigrationPlan {
  const mode = options.destructive ?? "comment-out";
  const diff = precomputedDiff ?? diffSchemas(base, target);
  const get = (category: DiffItem["category"], status: DiffItem["status"]) => diff.items.filter((i) => i.category === category && i.status === status);
  const steps: MigrationStep[] = [];
  const add = (title: string, objects: string[], sql: string, destructive = false, notes: string[] = [], reason = "Can permanently lose data.") => {
    if (!sql.trim()) return;
    const finalSql = destructive && mode === "comment-out" ? commentOut(sql, reason) : sql;
    steps.push({ order: steps.length + 1, title, objects, sql: finalSql, destructive, notes });
  };

  const removedFks = [...get("foreign_key", "removed"), ...get("foreign_key", "modified")];
  add("Drop foreign keys that are removed or changed", removedFks.map((i) => `${i.table}.${i.name}`),
    removedFks.map((i) => dropConstraint(asTable("", i), (i.before as FkPayload).name, "foreign key")).join("\n"));

  const droppedIdx = [...get("index", "removed"), ...get("index", "modified")];
  add("Drop indexes that are removed or changed", droppedIdx.map((i) => `${i.table}.${i.name}`),
    droppedIdx.map((i) => `DROP INDEX ${quoteIdent(i.name)} ON ${asTable("", i)};`).join("\n"));

  const dropCons = (["unique_constraint", "check_constraint", "default_constraint"] as const).flatMap((c) => [...get(c, "removed"), ...get(c, "modified")]);
  add("Drop constraints that are removed or changed", dropCons.map((i) => `${i.table}.${i.name}`),
    dropCons.map((i) => dropConstraint(asTable("", i), (i.before as SnapConstraint).name, i.category.replace("_", " "))).join("\n"));

  const dropPk = [...get("primary_key", "removed"), ...get("primary_key", "modified")];
  add("Drop primary keys that are removed or changed", dropPk.map((i) => i.table ?? i.name),
    dropPk.map((i) => dropConstraint(asTable("", i), (i.before as PrimaryKeyPayload).name, "primary key")).join("\n"),
    false, ["Foreign keys referencing the key must already be dropped (see earlier step)."]);

  for (const type of ["trigger", "view", "procedure", "function"] as const) {
    const removed = get(type, "removed");
    add(`Drop removed ${type}s`, removed.map((i) => i.name),
      removed.map((i) => `DROP ${routineKeyword(type)} ${tableSql(i.name)};`).join("\nGO\n"), false,
      ["Dependent objects and application code may break."]);
  }

  const addedSchemas = get("schema", "added");
  add("Create new schemas", addedSchemas.map((i) => i.name),
    addedSchemas.map((i) => `EXEC(N'CREATE SCHEMA ${quoteIdent(i.name)}');`).join("\n"));

  const addedTables = get("table", "added");
  const tableNotes: string[] = [];
  const createTables = addedTables.map((i) => {
    const o = i.after as SnapObject;
    const cols = [...o.columns].sort((a, b) => a.ordinal - b.ordinal);
    if (cols.some((c) => c.identity)) tableNotes.push("IDENTITY seed/increment are not captured in the metadata; (1,1) is assumed - verify.");
    return `CREATE TABLE ${tableSql(i.name)} (\n${cols.map((c) => `  ${columnDef(c)}`).join(",\n")}\n);`;
  });
  add("Create new tables", addedTables.map((i) => i.name), createTables.join("\n\n"), false, [...new Set(tableNotes)]);

  // columns
  const colAdds = get("column", "added").filter((i) => !addedTables.some((t) => t.name === i.table));
  add("Add new columns", colAdds.map((i) => `${i.table}.${i.name}`),
    colAdds.map((i) => `ALTER TABLE ${asTable("", i)} ADD ${columnDef(i.after as SnapColumn)};${i.riskNotes.length ? `  -- WARNING: ${i.riskNotes.join(" ")}` : ""}`).join("\n"),
    false, colAdds.flatMap((i) => i.riskNotes));

  const colMods = get("column", "modified");
  const colModSql: string[] = [];
  const colModNotes: string[] = [];
  let colModDestructive = false;
  for (const i of colMods) {
    const a = i.before as SnapColumn;
    const b = i.after as SnapColumn;
    const t = asTable("", i);
    const typeChanged = formatDataType(a) !== formatDataType(b) || a.nullable !== b.nullable;
    if (b.computed || a.computed || a.identity !== b.identity) {
      colModSql.push(`-- MANUAL: ${t}.${quoteIdent(b.name)} - ${i.riskNotes.join(" ")}`);
    } else if (typeChanged) {
      colModSql.push(`ALTER TABLE ${t} ALTER COLUMN ${quoteIdent(b.name)} ${formatDataType(b)} ${b.nullable === false ? "NOT NULL" : "NULL"};`);
    }
    if (a.defaultValue?.replace(/\s/g, "").toLowerCase() !== b.defaultValue?.replace(/\s/g, "").toLowerCase() && !b.computed) {
      colModSql.push(`-- Default changed: ${a.defaultValue ?? "(none)"} -> ${b.defaultValue ?? "(none)"}. Default constraint names are not always captured; check sys.default_constraints.`);
      if (b.defaultValue) colModSql.push(`-- ALTER TABLE ${t} ADD DEFAULT ${b.defaultValue} FOR ${quoteIdent(b.name)};  (after dropping the old default)`);
    }
    if (i.destructive) colModDestructive = true;
    colModNotes.push(...i.riskNotes);
  }
  add("Alter changed columns", colMods.map((i) => `${i.table}.${i.name}`), colModSql.join("\n"), colModDestructive, [...new Set(colModNotes)], "Type narrowing / conversion can truncate or fail.");

  const colDrops = get("column", "removed");
  add("Drop removed columns", colDrops.map((i) => `${i.table}.${i.name}`),
    colDrops.map((i) => `ALTER TABLE ${asTable("", i)} DROP COLUMN ${quoteIdent(i.name)};`).join("\n"), true, ["Data in dropped columns cannot be recovered without a backup."], "All data in these columns is lost.");

  const addPk = [...get("primary_key", "added"), ...get("primary_key", "modified")];
  add("Create primary keys", addPk.map((i) => i.table ?? i.name),
    addPk.map((i) => {
      const pk = i.after as PrimaryKeyPayload;
      const tbl = i.table ?? "";
      return `ALTER TABLE ${asTable("", i)} ADD CONSTRAINT ${quoteIdent(pk.name ?? `PK_${tbl.split(".").pop()}`)} PRIMARY KEY (${pk.columns.map(quoteIdent).join(", ")});`;
    }).join("\n"));

  const addCons = (["unique_constraint", "check_constraint", "default_constraint"] as const).flatMap((c) => [...get(c, "added"), ...get(c, "modified")]);
  add("Create constraints", addCons.map((i) => `${i.table}.${i.name}`),
    addCons.map((i) => {
      const c = i.after as SnapConstraint;
      const t = asTable("", i);
      const nm = c.name ? `CONSTRAINT ${quoteIdent(c.name)} ` : "";
      if (c.type === "unique") return `ALTER TABLE ${t} ADD ${nm}UNIQUE (${c.columns.map(quoteIdent).join(", ")});`;
      if (c.type === "check") return `ALTER TABLE ${t} WITH CHECK ADD ${nm}CHECK (${c.expression ?? "/* expression unavailable */"});`;
      return `ALTER TABLE ${t} ADD ${nm}DEFAULT ${c.expression ?? "/* expression unavailable */"} FOR ${quoteIdent(c.columns[0] ?? "")};`;
    }).join("\n"), false, addCons.flatMap((i) => i.riskNotes));

  const addIdx = [...get("index", "added"), ...get("index", "modified")];
  add("Create indexes", addIdx.map((i) => `${i.table}.${i.name}`), addIdx.map((i) => indexSql(i.after as SnapIndex, asTable("", i))).join("\n"));

  const addFks = [...get("foreign_key", "added"), ...get("foreign_key", "modified")];
  add("Create foreign keys", addFks.map((i) => `${i.table}.${i.name}`), addFks.map((i) => fkSql(i.after as FkPayload, asTable("", i))).join("\n"), false, addFks.flatMap((i) => i.riskNotes));

  for (const type of ["function", "view", "procedure", "trigger"] as const) {
    const changed = [...get(type, "added"), ...get(type, "modified")];
    if (!changed.length) continue;
    const sql = changed.map((i) => {
      const def = (i.after as SnapObject).definition;
      if (!def) return `-- ${type} ${i.name}: definition was not captured during import; script manually.`;
      return `GO\n${i.status === "modified" ? toCreateOrAlter(def.trim()) : def.trim()}\nGO`;
    }).join("\n");
    add(`${changed.some((c) => c.status === "added") ? "Create / alter" : "Alter"} ${type}s`, changed.map((i) => i.name), sql, false,
      changed.flatMap((i) => i.riskNotes));
  }

  const dropTables = get("table", "removed");
  add("Drop removed tables", dropTables.map((i) => i.name),
    dropTables.map((i) => `DROP TABLE ${tableSql(i.name)};`).join("\n"), true, ["All rows in the table are permanently deleted."], "Drops the table and ALL of its data.");

  const dropSchemas = get("schema", "removed");
  add("Drop removed schemas", dropSchemas.map((i) => i.name), dropSchemas.map((i) => `DROP SCHEMA ${quoteIdent(i.name)};`).join("\n"), false, ["A schema can only be dropped once it is empty."]);

  const migrationSql = steps.length
    ? [BANNER, ...steps.map((s) => `-- Step ${s.order}: ${s.title}${s.destructive ? "  [DESTRUCTIVE]" : ""}\n${s.sql}`)].join("\n\n")
    : `${BANNER}\n\n-- No schema differences found: nothing to migrate.`;

  // rollback: the reverse diff, always with destructive statements commented out
  let rollbackSql = "";
  const rollbackNotes: string[] = [];
  if (diff.items.length && !options.skipRollback) {
    const reverse = generateMigrationBody(target, base);
    rollbackSql = `${BANNER}\n-- ROLLBACK SUGGESTION: this reverses the schema changes only. It does NOT restore data.\n\n${reverse}`;
    rollbackNotes.push("Rollback is a suggestion generated by reversing the schema diff; it cannot restore dropped data.");
  }
  const dataLoss = diff.items.filter((i) => i.destructive);
  for (const d of dataLoss) {
    rollbackNotes.push(`${d.category.replace("_", " ")} ${d.table ? `${d.table}.` : ""}${d.name} (${d.status}) - data lost by the forward migration cannot be recovered by the rollback script; restore from backup.`);
  }

  const pre: string[] = ["-- Pre-migration validation (read-only)"];
  const post: string[] = ["-- Post-migration validation (read-only)"];
  const affectedTables = new Set<string>();
  for (const i of diff.items) if (i.table) affectedTables.add(i.table);
  for (const i of diff.items) if (i.category === "table" && i.status !== "added") affectedTables.add(i.name);
  for (const t of affectedTables) {
    const stillExists = !dropTables.some((d) => d.name === t);
    pre.push(`SELECT N'${t}' AS table_name, COUNT_BIG(*) AS row_count FROM ${tableSql(t)};`);
    if (stillExists) post.push(`SELECT N'${t}' AS table_name, COUNT_BIG(*) AS row_count FROM ${tableSql(t)};  -- compare with the pre-migration count`);
  }
  for (const i of colMods) {
    const a = i.before as SnapColumn;
    const b = i.after as SnapColumn;
    const t = asTable("", i);
    const col = quoteIdent(b.name);
    if (a.nullable !== false && b.nullable === false) pre.push(`SELECT COUNT_BIG(*) AS null_rows_blocking_not_null FROM ${t} WHERE ${col} IS NULL;  -- must be 0`);
    if (b.maxLength != null && b.maxLength > 0 && (a.maxLength === -1 || (a.maxLength ?? 0) > b.maxLength)) pre.push(`SELECT COUNT_BIG(*) AS rows_too_long_for_${b.name} FROM ${t} WHERE LEN(${col}) > ${b.maxLength};  -- must be 0`);
    if (a.dataType.toLowerCase() !== b.dataType.toLowerCase()) pre.push(`SELECT COUNT_BIG(*) AS rows_failing_conversion FROM ${t} WHERE ${col} IS NOT NULL AND TRY_CONVERT(${formatDataType(b)}, ${col}) IS NULL;  -- must be 0`);
    post.push(`SELECT COLUMNPROPERTY(OBJECT_ID(N'${i.table}'), N'${b.name}', 'AllowsNull') AS allows_null;`);
  }
  for (const i of colDrops) pre.push(`SELECT COUNT_BIG(*) AS rows_with_data_in_${i.name} FROM ${asTable("", i)} WHERE ${quoteIdent(i.name)} IS NOT NULL;  -- data that will be lost`);
  for (const i of colAdds) post.push(`SELECT COL_LENGTH(N'${i.table}', N'${i.name}') AS column_exists;  -- not NULL when present`);
  for (const i of addedTables) post.push(`SELECT OBJECT_ID(N'${i.name}', N'U') AS table_exists;  -- not NULL when present`);
  for (const i of dropTables) {
    pre.push(`SELECT COUNT_BIG(*) AS rows_to_be_lost FROM ${tableSql(i.name)};`);
    post.push(`SELECT OBJECT_ID(N'${i.name}', N'U') AS table_exists;  -- NULL once dropped`);
  }
  for (const i of addFks) {
    const f = i.after as FkPayload;
    const child = asTable("", i);
    const parent = tableSql((f.targetFull ?? "").replace(/^\./, ""));
    const joinOn = f.sourceColumns.map((c, k) => `c.${quoteIdent(c)} = p.${quoteIdent(f.targetColumns[k] ?? c)}`).join(" AND ");
    const notNull = f.sourceColumns.map((c) => `c.${quoteIdent(c)} IS NOT NULL`).join(" AND ");
    if (parent && !addedTables.some((t) => t.name === i.table)) {
      pre.push(`SELECT COUNT_BIG(*) AS orphan_rows_for_${(f.name ?? "fk").replace(/\W/g, "_")} FROM ${child} c LEFT JOIN ${parent} p ON ${joinOn} WHERE ${notNull} AND p.${quoteIdent(f.targetColumns[0] ?? "")} IS NULL;  -- must be 0`);
    }
    post.push(`SELECT name, is_not_trusted FROM sys.foreign_keys WHERE name = N'${f.name ?? ""}';  -- is_not_trusted should be 0`);
  }
  for (const i of get("unique_constraint", "added")) {
    const c = i.after as SnapConstraint;
    pre.push(`SELECT ${c.columns.map(quoteIdent).join(", ")}, COUNT_BIG(*) AS duplicates FROM ${asTable("", i)} GROUP BY ${c.columns.map(quoteIdent).join(", ")} HAVING COUNT_BIG(*) > 1;  -- must return no rows`);
  }
  if (pre.length === 1) pre.push("-- No data-dependent checks were required for this change set.");
  if (post.length === 1) post.push("-- No object checks were required for this change set.");

  const objectsAffected = [...new Set(diff.items.filter((i) => i.status !== "unchanged").map((i) => (i.table ? `${i.table}` : i.name)))];
  const t = diff.totals;
  const risks = [...new Set(diff.items.flatMap((i) => [...(i.destructive ? [`DATA LOSS: ${i.category.replace("_", " ")} ${i.table ? `${i.table}.` : ""}${i.name} (${i.status})`] : []), ...i.riskNotes]))];

  return {
    title: "Schema migration",
    purpose: `Bring a database at the source schema version in line with the target schema version (${t.added} added, ${t.modified} modified, ${t.removed} removed).`,
    objectsAffected,
    expectedImpact: [
      `${t.added} additions, ${t.modified} modifications and ${t.removed} removals across ${objectsAffected.length} object(s).`,
      ...(diff.totals.destructive ? [`${diff.totals.destructive} operation(s) can permanently lose data${mode === "comment-out" ? " and are commented out in the script" : ""}.`] : []),
      "Altering columns and creating indexes/constraints can take locks and may be slow on large tables.",
    ],
    risks,
    prerequisites: [
      "A verified, restorable backup (or database snapshot) of the target database.",
      "The migration has been rehearsed on a non-production copy with representative data.",
      "A maintenance window if tables are large or heavily used.",
      "All pre-migration validation queries return the expected results.",
    ],
    steps,
    validationSteps: [
      "Run the pre-migration validation queries and record the results.",
      "Apply the migration one step at a time, reviewing the output of each.",
      "Run the post-migration validation queries and compare with the pre-migration results.",
      "Smoke-test the application paths that use the changed objects.",
    ],
    rollbackConsiderations: rollbackNotes.length ? rollbackNotes : ["No changes to roll back."],
    migrationSql,
    rollbackSql,
    preValidationSql: pre.join("\n"),
    postValidationSql: post.join("\n"),
    checklist: [
      "[ ] Backup taken and restore verified",
      "[ ] Script reviewed by a second engineer",
      "[ ] Rehearsed on a production-like copy",
      "[ ] Destructive statements reviewed and consciously enabled (they are commented out by default)",
      "[ ] Pre-migration validation queries executed and recorded",
      "[ ] Maintenance window / change ticket approved",
      "[ ] Migration executed step by step",
      "[ ] Post-migration validation queries executed",
      "[ ] Application smoke tests passed",
      "[ ] Rollback plan understood (data cannot be restored by the rollback script)",
    ],
    destructiveCount: diff.totals.destructive,
    requiresHumanReview: true,
  };
}

/** Body of a migration (steps only, destructive statements always commented out) used for rollback suggestions. */
function generateMigrationBody(from: SchemaSnapshot, to: SchemaSnapshot): string {
  const plan = generateMigration(from, to, { destructive: "comment-out", skipRollback: true });
  return plan.steps.map((s) => `-- Step ${s.order}: ${s.title}${s.destructive ? "  [DESTRUCTIVE]" : ""}\n${s.sql}`).join("\n\n");
}
